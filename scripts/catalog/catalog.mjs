const YAML_OPTIONS = { lineWidth: 0 };

function yamlDocs(header, docs) {
  const body = docs.map((d) => YAML.stringify(d, YAML_OPTIONS)).join("---\n");
  return `# ${header}\n${body}`;
}

export function renderStrimziTopics(catalog) {
  const { strimziClusterName, strimziNamespace } = catalog.cluster;
  const docs = resolveTopics(catalog).map((t) => ({
    apiVersion: "kafka.strimzi.io/v1beta2",
    kind: "KafkaTopic",
    metadata: {
      name: t.name,
      namespace: strimziNamespace,
      labels: {
        "strimzi.io/cluster": strimziClusterName,
        "app.kubernetes.io/part-of": "fintechbankx-event-streaming",
        "app.kubernetes.io/managed-by": "topic-catalog",
        "fintechbankx.io/topic-kind": t.kind,
        "fintechbankx.io/owner": t.owner,
      },
      annotations: {
        "fintechbankx.io/contract": t.contract,
        ...(t.eventType ? { "fintechbankx.io/event-type": t.eventType } : {}),
        ...(t.dlq ? { "fintechbankx.io/dlq": t.dlq } : {}),
      },
    },
    spec: {
      topicName: t.name,
      partitions: t.partitions,
      replicas: t.replicationFactor,
      config: {
        "cleanup.policy": t.cleanupPolicy,
        "retention.ms": t.retentionMs,
        "min.insync.replicas": t.minInsyncReplicas,
        "max.message.bytes": t.maxMessageBytes,
      },
    },
  }));
  return yamlDocs(GENERATED_HEADER, docs);
}

export function renderStrimziUsers(catalog) {
  const { strimziClusterName, strimziNamespace } = catalog.cluster;
  const access = resolveAccess(catalog);
  const docs = Object.entries(access).map(([serviceId, a]) => {
    const acls = [];
    for (const name of a.produce_topics) {
      acls.push({ resource: { type: "topic", name, patternType: "literal" }, operations: ["Write", "Describe"], host: "*" });
    }
    for (const name of a.consume_topics) {
      acls.push({ resource: { type: "topic", name, patternType: "literal" }, operations: ["Read", "Describe"], host: "*" });
    }
    for (const prefix of a.consumer_group_prefixes) {
      acls.push({ resource: { type: "group", name: prefix, patternType: "prefix" }, operations: ["Read", "Describe"], host: "*" });
    }
    return {
      apiVersion: "kafka.strimzi.io/v1beta2",
      kind: "KafkaUser",
      metadata: {
        name: serviceId,
        namespace: strimziNamespace,
        labels: {
          "strimzi.io/cluster": strimziClusterName,
          "app.kubernetes.io/part-of": "fintechbankx-event-streaming",
          "app.kubernetes.io/managed-by": "topic-catalog",
          "fintechbankx.io/service-id": serviceId,
          "fintechbankx.io/workload-namespace": a.kubernetes_namespace,
        },
        annotations: {
          "fintechbankx.io/service-account": a.service_account,
        },
      },
      spec: {
        authentication: { type: "tls" },
        authorization: { type: "simple", acls },
      },
    };
  });
  return yamlDocs(GENERATED_HEADER, docs);
}

/** Strimzi metrics ConfigMap from the JMX exporter rules (hostPort is for the standalone exporter only). */
export function renderMetricsConfigMap(catalog, jmxRulesText) {
  const rules = YAML.parse(jmxRulesText);
  if (!rules || !Array.isArray(rules.rules) || rules.rules.length === 0) {
    throw new Error("JMX exporter config has no rules");
  }
  const { hostPort: _ignored, ...agentConfig } = rules;
  const doc = {
    apiVersion: "v1",
    kind: "ConfigMap",
    metadata: {
      name: `${catalog.cluster.strimziClusterName}-kafka-metrics`,
      namespace: catalog.cluster.strimziNamespace,
      labels: {
        "app.kubernetes.io/part-of": "fintechbankx-event-streaming",
        "app.kubernetes.io/managed-by": "topic-catalog",
      },
    },
    data: {
      "kafka-metrics-config.yml": YAML.stringify(agentConfig, YAML_OPTIONS),
    },
  };
  return yamlDocs(`${GENERATED_HEADER} Source rules: monitoring/jmx/kafka.yml.`, [doc]);
}

/** Input list for scripts/kafka/create-topics.sh (tab separated). */
export function renderTopicsTsv(catalog) {
  const lines = [
    `# ${GENERATED_HEADER}`,
    "# Read by scripts/kafka/create-topics.sh. Columns (tab separated):",
    "# topic\tkind\tpartitions\treplication_factor\tmin_insync_replicas\tcleanup_policy\tretention_ms\tmax_message_bytes",
  ];
  for (const t of resolveTopics(catalog)) {
    lines.push(
      [t.name, t.kind, t.partitions, t.replicationFactor, t.minInsyncReplicas, t.cleanupPolicy, t.retentionMs, t.maxMessageBytes].join("\t"),
    );
  }
  return `${lines.join("\n")}\n`;
}

/** Per-service produce/consume topics for the Terraform msk-client-access module. */
export function renderClientAccessJson(catalog) {
  const doc = {
    _generated: GENERATED_HEADER,
    status: catalog.metadata?.status ?? "Proposed",
    services: resolveAccess(catalog),
  };
  return `${JSON.stringify(doc, null, 2)}\n`;
}

function mdCell(value) {
  return String(value).replace(/\|/g, "\\|");
}

export function renderMarkdown(catalog) {
  const topics = resolveTopics(catalog);
  const lines = [
    "# Topic catalog (generated)",
    "",
    `<!-- ${GENERATED_HEADER} -->`,
    "",
    `Status: **${catalog.metadata?.status ?? "Proposed"}**. Source: [topics/catalog.yaml](../catalog.yaml).`,
    "Defaults: replication factor " +
      `${catalog.defaults.replicationFactor}, min.insync.replicas ${catalog.defaults.minInsyncReplicas}, ` +
      "cleanup.policy delete. Record key: aggregateId. Producers: the owner only.",
    "",
    "| Topic | Kind | Owner (only producer) | Event type | Partitions | Retention (ms) | DLQ | Known consumers | Implementation |",
    "|---|---|---|---|---|---|---|---|---|",
  ];
  for (const t of topics) {
    const producers = t.kind === "event" ? t.owner : t.producers.length > 0 ? t.producers.join(", ") : "consumers of the namespace (none yet)";
    const consumers =
      t.kind === "dlq"
        ? t.producers.length > 0
          ? `${t.producers.join(", ")} (redrive)`
          : "consumers of the namespace (none yet)"
        : t.consumers.length > 0
          ? t.consumers.map((c) => `${c.service} (\`${c.group}\`)`).join(", ")
          : `${t.consumersStatus} (none in code)`;
    lines.push(
      `| \`${t.name}\` | ${t.kind} | ${mdCell(producers)} | ${t.eventType ? `\`${t.eventType}\`` : "-"} | ${t.partitions} | ${t.retentionMs} | ${t.dlq ? `\`${t.dlq}\`` : "-"} | ${mdCell(consumers)} | ${t.implementation} |`,
    );
  }
  lines.push("", "## Gaps (not provisioned)", "", "| Service | Namespace | Reason |", "|---|---|---|");
  for (const g of catalog.gaps ?? []) {
    lines.push(`| ${g.service} | \`${g.namespace}\` | ${mdCell(g.reason.trim())} |`);
  }
  return `${lines.join("\n")}\n`;
}

/**
 * Every generated file, keyed by repository-relative path.
 * @param {string} root repository root
 */
export function generateAll(root, catalog) {
  const jmx = fs.readFileSync(path.join(root, "monitoring/jmx/kafka.yml"), "utf8");
  return new Map([
    ["deploy/strimzi/generated/kafka-topics.yaml", renderStrimziTopics(catalog)],
    ["deploy/strimzi/generated/kafka-users.yaml", renderStrimziUsers(catalog)],
    ["deploy/strimzi/generated/kafka-metrics-configmap.yaml", renderMetricsConfigMap(catalog, jmx)],
    ["topics/generated/topics.tsv", renderTopicsTsv(catalog)],
    ["topics/generated/msk-client-access.json", renderClientAccessJson(catalog)],
    ["topics/generated/TOPIC_CATALOG.md", renderMarkdown(catalog)],
  ]);
}

// ---------------------------------------------------------------------------
// Optional cross-check against the AsyncAPI catalog (local use; not a CI gate)
// ---------------------------------------------------------------------------

/**
 * Compares catalog topics with the channels of asyncapi/<owner>.yaml files in
 * a checkout of the AsyncAPI catalog. Returns error strings.
 */
export function crossCheckAsyncApi(catalog, asyncapiDir) {
  const errors = [];
  const resolved = resolveTopics(catalog);
  for (const ns of catalog.namespaces) {
    const file = path.join(asyncapiDir, `${ns.owner}.yaml`);
    if (!fs.existsSync(file)) {
      errors.push(`${ns.namespace}: contract ${ns.owner}.yaml not found in ${asyncapiDir}`);
      continue;
    }
    const spec = YAML.parse(fs.readFileSync(file, "utf8"));
    if (spec?.info?.["x-event-namespace"] && spec.info["x-event-namespace"] !== ns.namespace) {
      errors.push(`${ns.namespace}: contract declares x-event-namespace ${spec.info["x-event-namespace"]}`);
    }
    const channels = new Map();
    for (const ch of Object.values(spec?.channels ?? {})) {
      channels.set(ch.address, ch.bindings?.kafka ?? {});
    }
    const expected = resolved.filter((t) => t.namespace === ns.namespace);
    for (const t of expected) {
      const b = channels.get(t.name);
      if (!b) {
        errors.push(`${t.name}: no channel in ${ns.owner}.yaml`);
        continue;
      }
      if (b.partitions !== undefined && b.partitions !== t.partitions) {
        errors.push(`${t.name}: partitions ${t.partitions} in catalog, ${b.partitions} in contract`);
      }
      if (b.replicas !== undefined && b.replicas !== t.replicationFactor) {
        errors.push(`${t.name}: replicas ${t.replicationFactor} in catalog, ${b.replicas} in contract`);
      }
      const cfg = b.topicConfiguration ?? {};
      if (cfg["retention.ms"] !== undefined && cfg["retention.ms"] !== t.retentionMs) {
        errors.push(`${t.name}: retention.ms ${t.retentionMs} in catalog, ${cfg["retention.ms"]} in contract`);
      }
      const policy = cfg["cleanup.policy"];
      if (policy !== undefined && JSON.stringify(policy) !== JSON.stringify([t.cleanupPolicy])) {
        errors.push(`${t.name}: cleanup.policy ${t.cleanupPolicy} in catalog, ${JSON.stringify(policy)} in contract`);
      }
      channels.delete(t.name);
    }
    for (const address of channels.keys()) {
      errors.push(`${address}: channel in ${ns.owner}.yaml but not in the catalog`);
    }
  }
  return errors;
}
