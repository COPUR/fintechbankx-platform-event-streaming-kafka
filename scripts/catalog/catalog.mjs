// Topic catalog library: load, validate and render topics/catalog.yaml.
//
// Pure functions (no network, no cluster access). The CLI in generate.mjs
// writes or checks the rendered files; tests in test/catalog.test.mjs.

import fs from "node:fs";
import path from "node:path";
import YAML from "yaml";

export const TOPIC_PATTERN = /^evt\.[a-z]+\.[a-z0-9]+(?:-[a-z0-9]+)*\.[a-z0-9]+(?:-[a-z0-9]+)*\.v[0-9]+$/;
export const NAMESPACE_PATTERN = /^evt\.[a-z]+\.[a-z0-9]+(?:-[a-z0-9]+)*$/;
export const EVENT_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
export const EVENT_TYPE_PATTERN = /^[A-Z][A-Za-z]*\.[A-Z][A-Za-z]*\.[A-Z][A-Za-z]*\.v[0-9]+$/;
export const SERVICE_ID_PATTERN = /^svc-[a-z]+-[a-z0-9-]+$/;
export const K8S_NAME_PATTERN = /^[a-z0-9]([-a-z0-9]*[a-z0-9])?$/;
export const IMPLEMENTATIONS = ["outbox-relay", "debezium-outbox", "legacy-topic", "contract-only"];
export const CONSUMER_STATUSES = ["known", "unknown"];
export const MAX_TOPIC_LENGTH = 249;

export const GENERATED_HEADER =
  "Generated by scripts/catalog/generate.mjs from topics/catalog.yaml. Do not edit; run `npm run catalog:generate`.";

// ---------------------------------------------------------------------------
// Loading
// ---------------------------------------------------------------------------

export function loadCatalog(filePath) {
  const doc = YAML.parseDocument(fs.readFileSync(filePath, "utf8"));
  if (doc.errors.length > 0) {
    throw new Error(`${filePath}: ${doc.errors[0].message}`);
  }
  return doc.toJS();
}

/** Parses the bootstrap manifest CSV (no quoted fields in it) into a Map keyed by service_id. */
export function parseManifest(csvText) {
  const lines = csvText.split(/\r?\n/).filter((l) => l.trim() !== "");
  if (lines.length === 0) {
    throw new Error("manifest is empty");
  }
  const header = lines[0].split(",").map((h) => h.trim());
  for (const required of ["service_id", "event_namespace"]) {
    if (!header.includes(required)) {
      throw new Error(`manifest header lacks column ${required}`);
    }
  }
  const rows = new Map();
  for (const line of lines.slice(1)) {
    const cells = line.split(",");
    if (cells.length !== header.length) {
      throw new Error(`manifest row has ${cells.length} cells, header has ${header.length}: ${line}`);
    }
    const row = Object.fromEntries(header.map((h, i) => [h, cells[i].trim()]));
    rows.set(row.service_id, row);
  }
  return rows;
}

export function loadManifest(filePath) {
  return parseManifest(fs.readFileSync(filePath, "utf8"));
}

